/** t('key', { n: 3 }) in the chosen language. Objects are returned as is. */
export function makeT(lang) {
  const table = STRINGS[lang] || STRINGS.nl;
  return (key, vars = {}) => {
    const v = table[key] ?? STRINGS.nl[key] ?? key;
    if (typeof v !== 'string') return v;
    return v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
  };
}

export const euro = (lang, v) => {
  const n = Number(v) || 0;
  return lang === 'nl' ? `€${n.toFixed(2).replace('.', ',')}` : `€${n.toFixed(2)}`;
};
